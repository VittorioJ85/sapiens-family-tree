-- Sort a display copy so deterministic surname assignment keeps its stable order.
function catalog:sortedNames(names)
    local result={}
    for i,name in ipairs(names or {}) do result[i]=name end
    table.sort(result,function(a,b)
        local lowerA,lowerB=string.lower(a),string.lower(b)
        if lowerA==lowerB then return a<b end
        return lowerA<lowerB
    end)
    return result
end
function catalog:selection(settings)
    if settings and settings.cultures then return settings.cultures end
    local key=settings and settings.culture or "mixed"
    if key=="mixed" then return {roman=true,greek=true} end
    return {[key]=true}
end
function catalog:pool(settings)
    local enabled=self:selection(settings)
    local excluded=settings and settings.excludedNames or {}
    local pool,seen={},{}
    for _,key in ipairs(self.order) do
        if enabled[key] then
            local names=key=="custom" and (settings.customNames or {}) or self.names[key]
            for _,name in ipairs(names or {}) do
                if not excluded[name] and not seen[name] then pool[#pool+1]=name; seen[name]=true end
            end
        end
    end
    return pool
end
return catalog
